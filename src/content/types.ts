export interface Item {
  id: string
  /** Название в единственном числе, с маленькой буквы. Первая буква используется в игре «Слово на букву». */
  name: string
  emoji: string
  cats: Cat[]
  tags?: Tag[]
  /** Какой звук издаёт: «мяу», «гав». Используется в загадках и в «Кто я?». */
  sound?: string
  /** Где живёт или где встречается: «в лесу», «в воде», «дома». */
  where?: string
  color?: string
  /** Чем питается: «траву», «листья». */
  eats?: string
  /** Дополнительные приметы для «Кто я?»: «у него длинный нос». */
  facts?: string[]
  /** Годится, чтобы изобразить без слов. */
  show?: boolean
}
